SET FOREIGN_KEY_CHECKS = 0;
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

DROP PROCEDURE IF EXISTS AddCoursePrereq;

DELIMITER $$
CREATE PROCEDURE AddCoursePrereq(
    IN p_course_code VARCHAR(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN p_prereq_code VARCHAR(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN p_rule_type VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN p_min_grade VARCHAR(10) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci
)
BEGIN
    DECLARE v_course_id BIGINT;
    DECLARE v_prereq_id BIGINT;

    SELECT id INTO v_course_id FROM courses WHERE code COLLATE utf8mb4_0900_ai_ci = p_course_code COLLATE utf8mb4_0900_ai_ci LIMIT 1;
    SELECT id INTO v_prereq_id FROM courses WHERE code COLLATE utf8mb4_0900_ai_ci = p_prereq_code COLLATE utf8mb4_0900_ai_ci LIMIT 1;

    IF v_course_id IS NOT NULL AND v_prereq_id IS NOT NULL THEN
        INSERT INTO course_prerequisites (course_id, prerequisite_course_id, rule_type, min_grade_required)
        VALUES (v_course_id, v_prereq_id, p_rule_type, p_min_grade)
        ON DUPLICATE KEY UPDATE 
            rule_type = p_rule_type,
            min_grade_required = p_min_grade;
    END IF;
END $$
DELIMITER ;

